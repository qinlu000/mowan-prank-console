const fs = require("node:fs");
const path = require("node:path");
const { randomBytes } = require("node:crypto");

function usage() {
  console.log(`Usage:
  node scripts/create-production-env.js --domain <domain> [options]

Options:
  --admin <username>       Admin username. Default: admin
  --password <password>    Admin password. Default: generated
  --retention <days>       Session retention days. Default: 7
  --output <path>          Env file path. Default: .env
  --force                  Overwrite output if it already exists
`);
}

function parseArgs(argv) {
  const options = {
    admin: "admin",
    output: ".env",
    retention: "7",
    force: false
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--help" || arg === "-h") {
      options.help = true;
      continue;
    }

    if (arg === "--force") {
      options.force = true;
      continue;
    }

    if (!arg.startsWith("--")) {
      throw new Error(`Unexpected argument: ${arg}`);
    }

    const key = arg.slice(2);
    const value = argv[index + 1];
    if (!value || value.startsWith("--")) {
      throw new Error(`Missing value for ${arg}`);
    }
    index += 1;
    options[key] = value;
  }

  return options;
}

function randomSecret(byteLength = 32) {
  return randomBytes(byteLength).toString("base64url");
}

function assertEnvValue(name, value) {
  if (!String(value || "").trim()) {
    throw new Error(`${name} cannot be empty`);
  }
  if (String(value).includes("\n") || String(value).includes("\r")) {
    throw new Error(`${name} cannot contain line breaks`);
  }
}

function assertAdminPart(name, value) {
  assertEnvValue(name, value);
  if (String(value).includes(",") || String(value).includes(":")) {
    throw new Error(`${name} cannot contain "," or ":" because ADMIN_USERS uses "user:password" pairs`);
  }
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help || options.h) {
    usage();
    return;
  }

  if (!options.domain) {
    usage();
    throw new Error("Missing required --domain");
  }

  const domain = options.domain.trim();
  const admin = options.admin.trim();
  const password = options.password || randomSecret(18);
  const cookieSecret = randomSecret(48);
  const retention = String(options.retention || "7").trim();
  const outputPath = path.resolve(process.cwd(), options.output);

  assertEnvValue("DOMAIN", domain);
  assertAdminPart("admin username", admin);
  assertAdminPart("admin password", password);
  assertEnvValue("COOKIE_SECRET", cookieSecret);
  if (!/^[1-9]\d*$/.test(retention)) {
    throw new Error("SESSION_RETENTION_DAYS must be a positive integer");
  }

  if (fs.existsSync(outputPath) && !options.force) {
    throw new Error(`${outputPath} already exists. Pass --force to overwrite it.`);
  }

  const content = [
    "# Generated by scripts/create-production-env.js",
    `DOMAIN=${domain}`,
    `ADMIN_USERS=${admin}:${password}`,
    `COOKIE_SECRET=${cookieSecret}`,
    `SESSION_RETENTION_DAYS=${retention}`,
    ""
  ].join("\n");

  fs.writeFileSync(outputPath, content, "utf8");
  console.log(`Production env written to ${outputPath}`);
  console.log(`Admin username: ${admin}`);
  console.log(`Admin password: ${password}`);
}

try {
  main();
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
